use serde::{Deserialize, Serialize};
use super::atlas::PackedFrameItem;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CollisionFeetSettings {
    pub enabled: bool,
    pub shape: String, // "capsule" or "rectangle"
    pub width: f32,
    pub height: f32,
    pub offset_x: f32,
    pub offset_y: f32,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CollisionBoxSettings {
    pub enabled: bool,
    pub width: f32,
    pub height: f32,
    pub offset_x: f32,
    pub offset_y: f32,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GodotCollisionConfig {
    pub enabled: bool,
    pub feet: CollisionFeetSettings,
    pub hurtbox: CollisionBoxSettings,
    pub hitbox: CollisionBoxSettings,
}

pub fn generate_sprite_frames_tres(
    animation_name: &str,
    atlas_filename: &str,
    frame_width: u32,
    frame_height: u32,
    columns: u32,
    frames_count: usize,
    fps: f32,
    pivot: (f32, f32),
    packed_frames: Option<&[PackedFrameItem]>,
    frame_indices_map: Option<&[usize]>,
) -> String {
    let clean_anim_name = if animation_name.is_empty() { "default" } else { animation_name };
    let total_frames = if let Some(pf) = packed_frames {
        pf.len()
    } else {
        frames_count
    };
    let load_steps = total_frames + 2;

    let pivot_px_x = pivot.0 * frame_width as f32;
    let pivot_px_y = pivot.1 * frame_height as f32;

    let mut lines = Vec::new();
    lines.push(format!("[gd_resource type=\"SpriteFrames\" load_steps={} format=3]", load_steps));
    lines.push(format!("; Generated by SpriteForge Studio (Rust Engine) with Pivot ({:.2}, {:.2}) -> Vector2({:.1}, {:.1})", pivot.0, pivot.1, pivot_px_x, pivot_px_y));
    lines.push(String::new());
    lines.push(format!("[ext_resource type=\"Texture2D\" path=\"{}\" id=\"1_atlas\"]", atlas_filename));
    lines.push(String::new());

    for i in 0..total_frames {
        lines.push(format!("[sub_resource type=\"AtlasTexture\" id=\"AtlasTexture_{}\"]", i));
        lines.push("atlas = ExtResource(\"1_atlas\")".to_string());
        if let Some(pf) = packed_frames.and_then(|frames| frames.get(i)) {
            lines.push(format!("region = Rect2({}, {}, {}, {})", pf.x, pf.y, pf.width, pf.height));
            let margin_r = pf.source_width.saturating_sub(pf.width).saturating_sub(pf.offset_x);
            let margin_b = pf.source_height.saturating_sub(pf.height).saturating_sub(pf.offset_y);
            lines.push(format!("margin = Rect2({}, {}, {}, {})", pf.offset_x, pf.offset_y, margin_r, margin_b));
        } else {
            let col = i as u32 % columns.max(1);
            let row = i as u32 / columns.max(1);
            let x = col * frame_width;
            let y = row * frame_height;
            lines.push(format!("region = Rect2({}, {}, {}, {})", x, y, frame_width, frame_height));
        }
        lines.push(String::new());
    }

    lines.push("[resource]".to_string());
    lines.push("animations = [{".to_string());
    lines.push("\"frames\": [".to_string());

    for i in 0..frames_count {
        let is_last = i == frames_count - 1;
        let unique_idx = if let Some(map) = frame_indices_map {
            map.get(i).copied().unwrap_or(i)
        } else {
            i
        };
        lines.push("{".to_string());
        lines.push("\"duration\": 1.0,".to_string());
        lines.push(format!("\"texture\": SubResource(\"AtlasTexture_{}\")", unique_idx));
        lines.push(format!("}}{}", if is_last { "" } else { "," }));
    }

    lines.push("],".to_string());
    lines.push("\"loop\": true,".to_string());
    lines.push(format!("\"name\": &\"{}\",", clean_anim_name));
    lines.push(format!("\"speed\": {:.1}", fps));
    lines.push("}]".to_string());

    lines.join("\n")
}
