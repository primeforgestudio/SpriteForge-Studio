import { AtlasSettings, PackedFrameItem, SpriteMesh } from './types';

export class GodotExporter {
  /**
   * Generates a native Godot 4 text-based SpriteFrames (.tres) resource
   */
  public static generateSpriteFramesTres(
    animationName: string,
    atlasFilename: string,
    settings: AtlasSettings,
    framesCount: number,
    fps: number,
    packedFrames?: PackedFrameItem[],
    frameIndicesMap?: number[]
  ): string {
    const { frameWidth, frameHeight, columns } = settings;
    const cleanAnimName = animationName.replace(/\.[^/.]+$/, '').replace(/[^a-zA-Z0-9_]/g, '_') || 'default';
    const uniqueFramesCount = frameIndicesMap
      ? new Set(frameIndicesMap).size
      : (packedFrames ? packedFrames.length : Math.min(framesCount, settings.columns * settings.rows));
    const totalFrames = packedFrames ? packedFrames.length : uniqueFramesCount;
    const loadSteps = totalFrames + 2;

    const lines: string[] = [];

    const pivot = settings.pivot || { x: 0.5, y: 0.95 };
    const pivotPxX = (pivot.x * frameWidth).toFixed(1);
    const pivotPxY = (pivot.y * frameHeight).toFixed(1);

    // Header
    lines.push(`[gd_resource type="SpriteFrames" load_steps=${loadSteps} format=3]`);
    lines.push(`; Generated by SpriteForge with Pivot (${pivot.x.toFixed(2)}, ${pivot.y.toFixed(2)}) -> Vector2(${pivotPxX}, ${pivotPxY})`);
    lines.push('');
    // ExtResource: Texture2D pointing to the atlas png
    lines.push(`[ext_resource type="Texture2D" path="${atlasFilename}" id="1_atlas"]`);
    lines.push('');

    // SubResources: AtlasTexture for each frame in atlas
    for (let i = 0; i < totalFrames; i++) {
      lines.push(`[sub_resource type="AtlasTexture" id="AtlasTexture_${i}"]`);
      lines.push('atlas = ExtResource("1_atlas")');
      if (packedFrames && packedFrames[i]) {
        const pf = packedFrames[i];
        lines.push(`region = Rect2(${pf.x}, ${pf.y}, ${pf.width}, ${pf.height})`);
        const marginR = pf.sourceWidth - pf.width - pf.offsetX;
        const marginB = pf.sourceHeight - pf.height - pf.offsetY;
        lines.push(`margin = Rect2(${pf.offsetX}, ${pf.offsetY}, ${marginR}, ${marginB})`);
      } else {
        const col = i % columns;
        const row = Math.floor(i / columns);
        const x = col * frameWidth;
        const y = row * frameHeight;
        lines.push(`region = Rect2(${x}, ${y}, ${frameWidth}, ${frameHeight})`);
      }
      lines.push('');
    }

    // Main Resource block
    lines.push('[resource]');
    lines.push('animations = [{');
    lines.push('"frames": [');

    for (let i = 0; i < framesCount; i++) {
      const isLast = i === framesCount - 1;
      const uniqueIdx = frameIndicesMap && frameIndicesMap[i] !== undefined ? frameIndicesMap[i] : i;
      lines.push(`{`);
      lines.push(`"duration": 1.0,`);
      lines.push(`"texture": SubResource("AtlasTexture_${uniqueIdx}")`);
      lines.push(`}${isLast ? '' : ','}`);
    }

    lines.push('],');
    lines.push('"loop": true,');
    lines.push(`"name": &"${cleanAnimName}",`);
    lines.push(`"speed": ${fps.toFixed(1)}`);
    lines.push('}]');

    return lines.join('\n');
  }

  /**
   * Generates a native Godot 4 multi-animation SpriteFrames (.tres) resource for master atlases
   */
  public static generateMultiTrackSpriteFramesTres(
    atlasFilename: string,
    settings: AtlasSettings,
    tracksMeta: {
      name: string;
      fps: number;
      loop: boolean;
      frameIndices: number[];
    }[],
    packedFrames?: PackedFrameItem[],
    frameIndicesMap?: number[]
  ): string {
    const { frameWidth, frameHeight, columns } = settings;
    const totalInputFrames = tracksMeta.reduce((acc, t) => acc + t.frameIndices.length, 0);
    const uniqueCount = frameIndicesMap ? new Set(frameIndicesMap).size : (packedFrames ? packedFrames.length : totalInputFrames);
    const totalFrames = packedFrames ? packedFrames.length : uniqueCount;
    const loadSteps = totalFrames + 2;

    const lines: string[] = [];

    const pivot = settings.pivot || { x: 0.5, y: 0.95 };
    const pivotPxX = (pivot.x * frameWidth).toFixed(1);
    const pivotPxY = (pivot.y * frameHeight).toFixed(1);

    // Header
    lines.push(`[gd_resource type="SpriteFrames" load_steps=${loadSteps} format=3]`);
    lines.push(`; Generated by SpriteForge Multi-Track Master Atlas with Pivot (${pivot.x.toFixed(2)}, ${pivot.y.toFixed(2)}) -> Vector2(${pivotPxX}, ${pivotPxY})`);
    lines.push('');
    lines.push(`[ext_resource type="Texture2D" path="${atlasFilename}" id="1_atlas"]`);
    lines.push('');

    // SubResources: AtlasTexture for each frame in atlas
    for (let i = 0; i < totalFrames; i++) {
      lines.push(`[sub_resource type="AtlasTexture" id="AtlasTexture_${i}"]`);
      lines.push('atlas = ExtResource("1_atlas")');
      if (packedFrames && packedFrames[i]) {
        const pf = packedFrames[i];
        lines.push(`region = Rect2(${pf.x}, ${pf.y}, ${pf.width}, ${pf.height})`);
        const marginR = pf.sourceWidth - pf.width - pf.offsetX;
        const marginB = pf.sourceHeight - pf.height - pf.offsetY;
        lines.push(`margin = Rect2(${pf.offsetX}, ${pf.offsetY}, ${marginR}, ${marginB})`);
      } else {
        const col = i % columns;
        const row = Math.floor(i / columns);
        const x = col * frameWidth;
        const y = row * frameHeight;
        lines.push(`region = Rect2(${x}, ${y}, ${frameWidth}, ${frameHeight})`);
      }
      lines.push('');
    }

    // Main Resource block
    lines.push('[resource]');
    lines.push('animations = [');

    tracksMeta.forEach((track, trackIdx) => {
      const isLastTrack = trackIdx === tracksMeta.length - 1;
      const cleanName = track.name.replace(/[^a-zA-Z0-9_]/g, '_') || `anim_${trackIdx}`;
      lines.push('{');
      lines.push('"frames": [');

      track.frameIndices.forEach((frameIdx, fIdx) => {
        const isLastFrame = fIdx === track.frameIndices.length - 1;
        const uniqueIdx = frameIndicesMap && frameIndicesMap[frameIdx] !== undefined ? frameIndicesMap[frameIdx] : frameIdx;
        lines.push('{');
        lines.push('"duration": 1.0,');
        lines.push(`"texture": SubResource("AtlasTexture_${uniqueIdx}")`);
        lines.push(`}${isLastFrame ? '' : ','}`);
      });

      lines.push('],');
      lines.push(`"loop": ${track.loop ? 'true' : 'false'},`);
      lines.push(`"name": &"${cleanName}",`);
      lines.push(`"speed": ${(track.fps || 12).toFixed(1)}`);
      lines.push(`}${isLastTrack ? '' : ','}`);
    });

    lines.push(']');

    return lines.join('\n');
  }

  /**
   * Generates a native Godot 4 CharacterBody2D (.tscn) scene file
   * complete with AnimatedSprite2D, feet CollisionShape2D, Hurtbox Area2D and Hitbox Area2D.
   */
  public static generateCharacterSceneTscn(
    sceneName: string,
    framesTresFilename: string,
    settings: AtlasSettings,
    defaultAnimName: string = 'idle',
    spriteMesh?: SpriteMesh
  ): string {
    const cleanSceneName =
      sceneName.replace(/\.[^/.]+$/, '').replace(/[^a-zA-Z0-9_]/g, '_') || 'Character';

    const collision = settings.collisionSettings || {
      enabled: true,
      generateTscn: true,
      feet: { enabled: true, shape: 'capsule', width: 28, height: 12, offsetX: 0, offsetY: -6 },
      hurtbox: { enabled: true, width: 36, height: 64, offsetX: 0, offsetY: -36 },
      hitbox: { enabled: false, width: 32, height: 32, offsetX: 28, offsetY: -32 },
    };

    const pivot = settings.pivot || { x: 0.5, y: 0.95 };
    // Offset for AnimatedSprite2D to align frame's pivot with node (0,0)
    const spriteOffsetX = -Math.round((pivot.x - 0.5) * settings.frameWidth);
    const spriteOffsetY = -Math.round((pivot.y - 0.5) * settings.frameHeight);

    const subResources: string[] = [];
    let subResCount = 0;

    // SubResource 1: Feet collision
    let feetResId = '';
    if (collision.feet.enabled) {
      subResCount++;
      if (collision.feet.shape === 'capsule') {
        feetResId = `CapsuleShape2D_feet`;
        const radius = (collision.feet.height / 2).toFixed(1);
        const height = Math.max(Number(radius) * 2, collision.feet.width).toFixed(1);
        subResources.push(
          `[sub_resource type="CapsuleShape2D" id="${feetResId}"]\nradius = ${radius}\nheight = ${height}\n`
        );
      } else {
        feetResId = `RectangleShape2D_feet`;
        subResources.push(
          `[sub_resource type="RectangleShape2D" id="${feetResId}"]\nsize = Vector2(${collision.feet.width.toFixed(1)}, ${collision.feet.height.toFixed(1)})\n`
        );
      }
    }

    // SubResource 2: Hurtbox
    let hurtboxResId = '';
    if (collision.hurtbox.enabled) {
      subResCount++;
      hurtboxResId = `CapsuleShape2D_hurtbox`;
      const radius = (collision.hurtbox.width / 2).toFixed(1);
      const height = Math.max(Number(radius) * 2, collision.hurtbox.height).toFixed(1);
      subResources.push(
        `[sub_resource type="CapsuleShape2D" id="${hurtboxResId}"]\nradius = ${radius}\nheight = ${height}\n`
      );
    }

    // SubResource 3: Hitbox
    let hitboxResId = '';
    if (collision.hitbox.enabled) {
      subResCount++;
      hitboxResId = `RectangleShape2D_hitbox`;
      subResources.push(
        `[sub_resource type="RectangleShape2D" id="${hitboxResId}"]\nsize = Vector2(${collision.hitbox.width.toFixed(1)}, ${collision.hitbox.height.toFixed(1)})\n`
      );
    }

    const loadSteps = subResCount + 2;

    const lines: string[] = [];
    lines.push(`[gd_scene load_steps=${loadSteps} format=3]`);
    lines.push(`; Generated by SpriteForge Studio for Godot 4`);
    lines.push('');
    lines.push(`[ext_resource type="SpriteFrames" path="${framesTresFilename}" id="1_frames"]`);
    lines.push('');

    for (const res of subResources) {
      lines.push(res);
    }

    // Root Node
    lines.push(`[node name="${cleanSceneName}" type="CharacterBody2D"]`);
    lines.push('collision_layer = 1');
    lines.push('collision_mask = 1');
    lines.push('');

    // AnimatedSprite2D Node
    lines.push(`[node name="AnimatedSprite2D" type="AnimatedSprite2D" parent="."]`);
    lines.push('sprite_frames = ExtResource("1_frames")');
    lines.push(`animation = &"${defaultAnimName}"`);
    lines.push(`autoplay = "${defaultAnimName}"`);
    lines.push(`offset = Vector2(${spriteOffsetX}, ${spriteOffsetY})`);
    lines.push('');

    // Optional High-Performance Polygon2D Node (Mobile & iGaming Overdraw Killer)
    if (spriteMesh && (settings.meshSettings?.enabled ?? true)) {
      lines.push(`; 2D Mesh Overdraw Optimizer (${spriteMesh.vertexCount} verts, ${spriteMesh.triangleCount} tris, ${spriteMesh.areaSavingsPercent}% fillrate saved)`);
      lines.push(`[node name="Polygon2D" type="Polygon2D" parent="."]`);
      lines.push('visible = false');

      const polyVerts = spriteMesh.vertices.map((v) => {
        const rx = (v[0] - pivot.x * settings.frameWidth).toFixed(1);
        const ry = (v[1] - pivot.y * settings.frameHeight).toFixed(1);
        return `${rx}, ${ry}`;
      });
      lines.push(`polygon = PackedVector2Array(${polyVerts.join(', ')})`);

      const uvs = spriteMesh.vertices.map((v) => `${v[0].toFixed(1)}, ${v[1].toFixed(1)}`);
      lines.push(`uv = PackedVector2Array(${uvs.join(', ')})`);

      const polyIndices: string[] = [];
      for (let i = 0; i < spriteMesh.indices.length; i += 3) {
        polyIndices.push(`PackedInt32Array(${spriteMesh.indices[i]}, ${spriteMesh.indices[i + 1]}, ${spriteMesh.indices[i + 2]})`);
      }
      lines.push(`polygons = [${polyIndices.join(', ')}]`);
      lines.push('');
    }

    // Feet CollisionShape2D Node
    if (collision.feet.enabled && feetResId) {
      lines.push(`[node name="CollisionShape2D" type="CollisionShape2D" parent="."]`);
      lines.push(
        `position = Vector2(${collision.feet.offsetX.toFixed(1)}, ${collision.feet.offsetY.toFixed(1)})`
      );
      if (collision.feet.shape === 'capsule') {
        lines.push(`rotation = 1.5708`);
      }
      lines.push(`shape = SubResource("${feetResId}")`);
      lines.push('');
    }

    // Hurtbox Node (Area2D)
    if (collision.hurtbox.enabled && hurtboxResId) {
      lines.push(`[node name="Hurtbox" type="Area2D" parent="."]`);
      lines.push('collision_layer = 2');
      lines.push('collision_mask = 0');
      lines.push('monitoring = false');
      lines.push('');
      lines.push(`[node name="CollisionShape2D" type="CollisionShape2D" parent="Hurtbox"]`);
      lines.push(
        `position = Vector2(${collision.hurtbox.offsetX.toFixed(1)}, ${collision.hurtbox.offsetY.toFixed(1)})`
      );
      lines.push(`shape = SubResource("${hurtboxResId}")`);
      lines.push('debug_color = Color(0, 0.6, 0.9, 0.42)');
      lines.push('');
    }

    // Hitbox Node (Area2D)
    if (collision.hitbox.enabled && hitboxResId) {
      lines.push(`[node name="Hitbox" type="Area2D" parent="."]`);
      lines.push('collision_layer = 0');
      lines.push('collision_mask = 2');
      lines.push('monitorable = true');
      lines.push('');
      lines.push(`[node name="CollisionShape2D" type="CollisionShape2D" parent="Hitbox"]`);
      lines.push(
        `position = Vector2(${collision.hitbox.offsetX.toFixed(1)}, ${collision.hitbox.offsetY.toFixed(1)})`
      );
      lines.push(`shape = SubResource("${hitboxResId}")`);
      lines.push('debug_color = Color(0.95, 0.2, 0.2, 0.42)');
      lines.push('');
    }

    return lines.join('\n');
  }
}
